// The bank of real-world commitments behind the onboarding picker: things a
// user likely pays for but won't all RECALL when staring at an empty list.
// Selecting one files it into the "To complete" list, which pre-fills the Add
// form. Names are plain text (nominative use); no logo artwork ships in the
// binary — platforms may fetch one at runtime from `domain`, falling back to
// the brand `color` + first letter. No amounts: they vary per person/tier.
//
// Curation rules:
// - Europe-centric; region-specific brands carry `regions` (ISO codes) and
//   are hidden outside those regions unless searched for.
// - `unit` is the cadence the thing is USUALLY billed on (pre-fills the form).
// - `color` only where the brand hex is confidently known; omitted = the
//   category's look. Generic entries (e.g. "Gym membership") cover the rest.

export interface SuggestedCommitment {
  /** Stable slug, also the pending-list id. */
  readonly id: string;
  readonly name: string;
  readonly categoryId?: string;
  /** The cadence this is USUALLY billed on — pre-fills the form. */
  readonly unit: "month" | "year";
  /** Brand hex (#RRGGBB) — badge fallback colour + the created item's accent. */
  readonly color?: string;
  /** Brand website — platforms may fetch a logo from it at runtime. */
  readonly domain?: string;
  /** Extra search terms ("Prime" → Amazon Prime). */
  readonly aliases?: readonly string[];
  /** ISO 3166-1 alpha-2 codes where this is relevant; absent = everywhere. */
  readonly regions?: readonly string[];
}

